/** R15Q3 export real SOURCE B48 playable meshes and measured original 240Hz
 * trajectory as technical geometry assets for editable Blender inspection.
 * NOT original WebGL or human gameplay, nor art approved.
 */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
import {buildR15Q,R15Q_MODES} from './p101-r15q-isolated-b48-scissor-c1-curve-and-narrow-route.mjs';
import {tessellate} from '../private/reference_only/director/surface.js';
const SHA='af076d67492a677d2235e4730aef8cdf4808e106';
const worlds=['true-pinch','pinch-switch'];
const args=process.argv.slice(2),get=k=>{const i=args.indexOf(k);assert.ok(i>=0,k);return args[i+1]};
const runs=JSON.parse(fs.readFileSync(get('--runs'),'utf8'));
assert.equal(runs.originalGameSourceBlob,SHA);
const root=get('--out');fs.mkdirSync(root,{recursive:true});
const manifest={schema:'dopagaki.r15q3-source-authored-real-b48-mesh-and-native-player-trail/1',
 originalGameSourceBlob:SHA,sourceRoadVariants:worlds,
 allFourTruePhysicalSourceC1Alternatives:Object.keys(R15Q_MODES),
 pairedRoadAssets:[],newGameColliders:0,sourceProgramUnchanged:true,
 originalWebGLRealGameRendered:false,artOrGameplayApproved:false};
function sha(v){return crypto.createHash('sha256').update(JSON.stringify(v)).digest('hex')}
function obj(roadSegments){
 let result=['# R15Q3 GENUINE B48 SOURCE MESH generated by untouched tessellate()', '# technical Blender-only, never a deployed game collider'];
 let offset=0,indices=[];
 for(const [index,s] of roadSegments){
  const m=tessellate(s);assert.equal(m.degenerate,0);
  result.push('o SOURCE_B48_'+index+'_'+s.id.replaceAll(' ','_'));
  for(let j=0;j<m.positions.length;j+=3)
   result.push('v '+m.positions.slice(j,j+3).map(x=>x.toFixed(6)).join(' '));
  result.push('g physics_rideable_'+s.id);
  for(let k=0;k<m.indices.length;k+=3)result.push(
   'f '+m.indices.slice(k,k+3).map(i=>i+1+offset).join(' '));
  indices.push({index,sourceRoadId:s.id,sourceOriginalTriangleCount:m.indices.length/3,
    sourceRealTopTriangleCount:m.topIndexCount/3});
  offset+=m.positions.length/3;
 }
 return {text:result.join('\n')+'\n',counts:indices};
}
for(const road of worlds){
 for(const mode of Object.keys(R15Q_MODES)){
  const doc=buildR15Q(road,mode);
  const base=path.join(root,road,mode);fs.mkdirSync(base,{recursive:true});
  const res=runs.nativeScissorRealEditableSurfaceGeometryTrials[road][mode];
  assert.equal(res.sourceWorld,road);
  assert.equal(res.sourceStudyName,mode);
  assert.equal(res.true240HzOriginalSourcePhysics.sourceBlob,SHA);
  const write=obj([[1,doc.surfaces[1]],[2,doc.surfaces[2]]]);
  const fname='R15Q3_SOURCE_B48_TWO_ACTUAL_ROAD_MESHES.obj';
  fs.writeFileSync(path.join(base,fname),write.text);
  const native=res.true240HzOriginalSourcePhysics;
  const samples=native.nativeQuarterSecondSourcePhysicsTrace;
  const originalGeo=res.actualPhysicalSCISSORSourceGeometry;
  const meta={
   schema:'dopagaki.r15q3-actual-source-b48-and-real-physics-trail-one/1',
   sourceGameBlob:SHA,road,mode,sourcePhysicsHz:240,
   originalSourceRoadMeshes:write.counts,
   originalCrownB16SourcePointsSHA256:sha(doc.surfaces[1].points),
   trueStudySCISSORSourcePointsSHA256:sha(doc.surfaces[2].points),
   originalSourceDynamicB51Count:doc.movingObstacles.length,
   originalSCISSORCurveWidthRows:originalGeo.isolatedTrueCrossSectionWidthPost,
   sourceActualNativeRunnerStatus:native.originalSourceStatus,
   sourceOriginalTerminalTimeSeconds:native.originalSourceTerminalTimeSeconds,
   sourceNativeLastSupported:native.nativePhysicalLastB48Support,
   actualOriginal240HzQuarterSecondSampledPlayerPositionAndSupport:samples,
   actualOriginalGameWebGLRendered:false,
   sourceRoadsInRenderedSceneOnly:[doc.surfaces[1].id,doc.surfaces[2].id],
   originalOtherFiveB48RoadsOmittedFromTechnicalCamera:true,
   noRealGameOrHumanVisualCertification:true,
   originalGameSourceEdited:false,newGameColliders:0,
   ART:'HOLD',GAMEPLAY:'HOLD',HUMAN:'HOLD'
  };
  fs.writeFileSync(path.join(base,'R15Q3_SOURCE_ROAD_AND_TRUE_240HZ_SAMPLE_TRAIL.json'),
   JSON.stringify(meta,null,2)+'\n');
  manifest.pairedRoadAssets.push({road,mode,relativeFolder:path.relative(root,base),
   actualSourceMeshOBJ:fname,
   B16CrownSourceHash:meta.originalCrownB16SourcePointsSHA256,
   sourceModifiedScissorHash:meta.trueStudySCISSORSourcePointsSHA256,
   sourceOriginalRoadTriangleCounts:write.counts,
   realNativeSampledTrailPoints:samples.length});
  console.log('R15Q3_TRUE_ORIGINAL_SOURCE_B48_3D_MESH_EXPORTED',road,mode,
    'triangles',JSON.stringify(write.counts),'trailPoints',samples.length);
 }
}
assert.equal(manifest.pairedRoadAssets.length,8);
for(const road of worlds){
 const four=manifest.pairedRoadAssets.filter(x=>x.road===road);
 assert.equal(new Set(four.map(x=>x.B16CrownSourceHash)).size,1);
 assert.equal(new Set(four.map(x=>x.sourceModifiedScissorHash)).size,4);
}
fs.writeFileSync(path.join(root,'R15Q3_SOURCE_EIGHT_REAL_MESH_SCENES_MANIFEST.json'),
 JSON.stringify(manifest,null,2)+'\n');
