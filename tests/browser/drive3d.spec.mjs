 await expect(page.locator('#runScore')).toHaveText(/^\d[\d,]*$/);
 const recorded=await page.evaluate(()=>localStorage.getItem('dopagaki:survival:1:EP-P66:0'));
 expect(recorded).toBeNull();
 await page.locator('#practiceRun').click();
