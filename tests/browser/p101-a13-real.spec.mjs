import {test,expect} from '@playwright/test';
import fs from 'node:fs/promises';
test('A13 isolated WebGL: 28 native solid machines, real narrowed roads, save and distinct B5 baseline',async({page},info)=>{
 test.setTimeout(120000);
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/drive3d/?stage=VB-P101-A13');
 await expect(page.locator('#stage')).toHaveValue('VB-P101-A13');
 await expect(page.locator('#appStatus')).toContainText('P101 A13',{timeout:90000});
 await expect(page.locator('#view')).toHaveAttribute('data-machine-count','28');
 await expect(page.locator('#view')).toHaveAttribute('data-hazard-station-count','28');
 await expect(page.locator('#view')).toHaveAttribute('data-a13-machine-architecture','16');
 await expect(page.locator('#view')).toHaveAttribute('data-a13-w9-facilities','2');
 await expect(page.locator('#view')).toHaveAttribute('data-a13-w9-sections','0,3');
 await expect(page.locator('#view')).toHaveAttribute('data-a13-w9-wall-plates','208');
 await expect(page.locator('#view')).toHaveAttribute('data-a13-w9-roof-plates','104');
 await expect(page.locator('#view')).toHaveAttribute('data-a13-w9-non-collision','true');
 await expect(page.locator('#view')).toHaveAttribute('data-a13-architecture-non-collision','true');
 await expect(page.locator('#view')).toHaveAttribute('data-a13-custom-moving-shapes','16');
 await expect(page.locator('#view')).toHaveAttribute('data-a13-version','W7F');
 await expect(page.locator('#view')).toHaveAttribute('data-a13-road-art-non-collision','true');
 await expect(page.locator('#view')).toHaveAttribute('data-a13-road-art-segments',/^[1-9][0-9]{2}$/);
 await expect(page.locator('#b5QaPanel')).toBeVisible();
 await expect(page.locator('#p101Profile')).toHaveValue('OVERDRIVE');
 const data=await page.evaluate(async()=>await (await fetch('../generated/P101_A13_W7_GAMEPLAY.json')).json());
 expect(data.stageForge.fullStartToFinish).toContain('SCRIPTED_ONLY');
 expect(data.stageForge.revision).toBe('W7F');
 expect(data.stageForge.nativeScriptedProof).toMatchObject({physicsHz:240,sections:7,movingColliders:28,elapsedSeconds:53.275});
 expect(data.stageForge.humanPlaytest).toBe('NOT_RUN');
 expect(data.stageForge.genuineFastLaw).toBeNull();
 expect(data.stageForge.productionPromoted).toBe(false);
 const w9x=await page.evaluate(async()=>await (await fetch('../generated/P101_A13_W9X_B1_TRIAL.json')).json());
 expect(w9x.stageForge.revision).toBe('W9-X-B1');
 expect(w9x.stageForge.recordStageId).toBe('VB-P101-A13-W9X-B1');
 expect(w9x.stageForge.humanPlaytest).toBe('NOT_RUN');
 expect(w9x.stageForge.productionPromoted).toBe(false);
 expect(w9x.stageForge.nativeScriptedProof).toBeNull();
 expect(w9x.movingObstacles).toEqual(data.movingObstacles);
 expect(w9x.route).toEqual(data.route);
 expect(w9x.surfaces.filter((s,i)=>i!==3)).toEqual(data.surfaces.filter((s,i)=>i!==3));
 expect(w9x.surfaces[3].points[77][1]).toBe(data.surfaces[3].points[77][1]);
 expect(w9x.surfaces[3].points[76][1]).not.toBe(data.surfaces[3].points[76][1]);
 expect(data.surfaces.length).toBe(7);
 expect(data.movingObstacles.length).toBe(28);
 await page.locator('#view').screenshot({path:info.outputPath('p101-a13-opening-webgl.png')});
 await page.locator('#spawn').selectOption('3');
 await expect(page.locator('#view')).toHaveAttribute('data-machine-count','28');
 await page.locator('#view').screenshot({path:info.outputPath('p101-a13-lower-reversal-webgl.png')});
 await page.keyboard.down('ArrowRight');
 await page.waitForFunction(()=>Number.parseFloat(document.querySelector('#simTime')?.textContent||'0')>1.1,null,{timeout:40000});
 await page.keyboard.up('ArrowRight');
 const download=page.waitForEvent('download');
 await page.locator('#b5QaExport').click();
 const d=await download;
 expect(d.suggestedFilename()).toMatch(/^P101_A13_W7F_MANUAL_QA_(ongoing|failed|finished)\.json$/);
 const qa=JSON.parse(await fs.readFile(await d.path(),'utf8'));
 expect(qa.schema).toBe('dopagaki.a13-manual-qa/1');
 expect(qa.stageId).toBe('VB-P101-A13-W7F');
 expect(qa.samples.length).toBeGreaterThan(0);
 await page.locator('#stage').selectOption('VB-P101-B5');
 await expect(page.locator('#view')).toHaveAttribute('data-machine-count','12');
 await expect(page.locator('#view')).toHaveAttribute('data-a13-custom-moving-shapes','0');
 await expect(page.locator('#view')).toHaveAttribute('data-a13-version','none');
 await expect(page.locator('#view')).toHaveAttribute('data-a13-road-art-segments','0');
 await expect(page.locator('#view')).toHaveAttribute('data-a13-w9-facilities','0');
 await expect(page.locator('#view')).toHaveAttribute('data-a13-w9-wall-plates','0');
 await expect(page.locator('#appStatus')).toContainText('B5 HYPER ARC');
 expect(errors).toEqual([]);
});
