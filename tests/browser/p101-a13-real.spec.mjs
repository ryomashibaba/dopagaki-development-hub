import {test,expect} from '@playwright/test';
import fs from 'node:fs/promises';
test('A13 isolated WebGL: 28 native solid machines, real narrowed roads, save and distinct B5 baseline',async({page},info)=>{
 test.setTimeout(120000);
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/drive3d/');
 await page.locator('#stage').selectOption('VB-P101-A13');
 await expect(page.locator('#appStatus')).toContainText('P101 A13',{timeout:90000});
 await expect(page.locator('#view')).toHaveAttribute('data-machine-count','28');
 await expect(page.locator('#view')).toHaveAttribute('data-hazard-station-count','28');
 await expect(page.locator('#view')).toHaveAttribute('data-a13-machine-architecture','16');
 await expect(page.locator('#view')).toHaveAttribute('data-a13-architecture-non-collision','true');
 await expect(page.locator('#view')).toHaveAttribute('data-a13-custom-moving-shapes','16');
 await expect(page.locator('#b5QaPanel')).toBeVisible();
 await expect(page.locator('#p101Profile')).toHaveValue('OVERDRIVE');
 const data=await page.evaluate(async()=>await (await fetch('../generated/P101_A13_GAMEPLAY_W1.json')).json());
 expect(data.stageForge.fullStartToFinish).toBe('NOT_VERIFIED_A13');
 expect(data.stageForge.humanPlaytest).toBe('NOT_RUN');
 expect(data.stageForge.genuineFastLaw).toBeNull();
 expect(data.stageForge.productionPromoted).toBe(false);
 expect(data.surfaces.length).toBe(7);
 expect(data.movingObstacles.length).toBe(28);
 await page.locator('#view').screenshot({path:info.outputPath('p101-a13-opening-webgl.png')});
 await page.locator('#spawn').selectOption('3');
 await expect(page.locator('#view')).toHaveAttribute('data-machine-count','28');
 await page.locator('#view').screenshot({path:info.outputPath('p101-a13-lower-reversal-webgl.png')});
 await page.keyboard.down('ArrowRight');
 await page.waitForFunction(()=>Number.parseFloat(document.querySelector('#simTime')?.textContent||'0')>1.1,null,{timeout:40000});
 await page.keyboard.up('ArrowRight');
 const download=page.waitForEvent('download');
 await page.locator('#b5QaExport').click();
 const d=await download;
 expect(d.suggestedFilename()).toMatch(/^P101_A13_MANUAL_QA_(ongoing|failed|finished)\.json$/);
 const qa=JSON.parse(await fs.readFile(await d.path(),'utf8'));
 expect(qa.schema).toBe('dopagaki.a13-manual-qa/1');
 expect(qa.stageId).toBe('VB-P101-A13');
 expect(qa.samples.length).toBeGreaterThan(0);
 await page.locator('#stage').selectOption('VB-P101-B5');
 await expect(page.locator('#view')).toHaveAttribute('data-machine-count','12');
 await expect(page.locator('#view')).toHaveAttribute('data-a13-custom-moving-shapes','0');
 await expect(page.locator('#appStatus')).toContainText('B5 HYPER ARC');
 expect(errors).toEqual([]);
});
