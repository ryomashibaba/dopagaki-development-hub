import {test,expect} from '@playwright/test';
import fs from 'node:fs/promises';
const stage=road=>'VB-P101-A13-W9C2-G4E7AK-'+road.toUpperCase();
const url=road=>'/drive3d/?g4e7al=manual&stage='+stage(road);
test('AL real 7AJ stage is not listed or playable without the manual localhost gate',async({page})=>{
 await page.goto('/drive3d/?stage='+stage('TRUE-PINCH'));
 await expect(page.locator('#stage')).toHaveValue('EP-P66');
 await expect(page.locator('#stage option[value^="VB-P101-A13-W9C2-G4E7AK"]')).toHaveCount(0);
 await expect(page.locator('#g4e7alPanel')).toHaveCount(0);
});
test('AL 2 real manual physics courses, A/D samples, export/continue, no human PASS',async({page},info)=>{
 test.setTimeout(180000);
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(url('TRUE-PINCH'));
 const view=page.locator('#view'),panel=page.locator('#g4e7alPanel');
 await expect(page.locator('#appStatus')).toContainText('G4E-7AL LOCAL MANUAL',{timeout:90000});
 await expect(panel).toBeVisible();
 await expect(view).toHaveAttribute('data-g4e7al-mode','human-keyboard-qa-only');
 await expect(view).toHaveAttribute('data-run-mode','private-real-B48-B51-AL-manual-HOLD');
 await expect(view).toHaveAttribute('data-machine-count','28');
 await expect(page.locator('#stage')).toBeDisabled();
 await expect(page.locator('#spawn')).toHaveValue('0');
 await expect(page.locator('#spawn')).toBeDisabled();
 await expect(page.locator('#p101Profile')).toHaveValue('OVERDRIVE');
 await expect(page.locator('#p101Profile')).toBeDisabled();
 await expect(page.locator('#cameraCompare')).toBeDisabled();
 await expect(page.locator('#demoRun')).toBeDisabled();
 await expect(page.locator('#g4e7alStep')).toContainText('1/2 TRUE-PINCH');
 await expect(page.locator('#g4e7alResultDownload')).toBeHidden();
 await page.keyboard.down('KeyD');
 await page.waitForTimeout(520);
 await page.keyboard.up('KeyD');
 await expect(page.locator('#g4e7alLive')).toContainText('B48');
 const dl0=page.waitForEvent('download');await page.locator('#g4e7alDownload').click();
 const snapshot=JSON.parse(await fs.readFile(await(await dl0).path(),'utf8'));
 expect(snapshot.runs).toHaveLength(0);
 expect(snapshot.uncommittedCurrentRun.road).toBe('true-pinch');
 expect(snapshot.uncommittedCurrentRun.source).toBe('LOCAL_MANUAL_INPUT_NO_P96');
 expect(snapshot.uncommittedCurrentRun.metrics.physicsSteps).toBeGreaterThan(0);
 expect(snapshot.uncommittedCurrentRun.metrics.activeDirectionalSteps).toBeGreaterThan(0);
 expect(snapshot.uncommittedCurrentRun.originalStart00).toBe(true);
 expect(snapshot.uncommittedCurrentRun.physicalCourse.realMovingB51).toBe(28);
 expect(snapshot.uncommittedCurrentRun.certifiedSlope2Meters).toBe(0);
 await page.locator('#g4e7alNoticed').selectOption('no');
 await page.locator('#g4e7alNote').fill('Automated Chromium UI; NOT a human QA assessment.');
 await page.locator('#g4e7alNext').click();
 await expect(page.locator('#appStatus')).toContainText('G4E-7AL LOCAL MANUAL',{timeout:90000});
 await expect(page.locator('#stage')).toHaveValue(stage('PINCH-SWITCH'));
 await expect(page.locator('#g4e7alStep')).toContainText('2/2 PINCH-SWITCH');
 await page.keyboard.down('ArrowLeft');await page.waitForTimeout(350);await page.keyboard.up('ArrowLeft');
 await page.screenshot({path:info.outputPath('g4e7al-private-manual-second-road.png')});
 await page.locator('#g4e7alFairness').selectOption('unsure');
 await page.locator('#g4e7alEnjoyment').selectOption('3');
 await page.locator('#g4e7alNext').click();
 await expect(page.locator('#g4e7alStep')).toContainText('比較2/2記録完了');
 await expect(page.locator('#g4e7alNext')).toBeDisabled();
 await expect(view).toHaveAttribute('data-g4e7al-mode','two-trials-recorded-hold');
 const dl=page.waitForEvent('download');await page.locator('#g4e7alDownload').click();
 const report=JSON.parse(await fs.readFile(await(await dl).path(),'utf8'));
 expect(report.completedBoth).toBe(true);
 expect(report.runs.map(x=>x.road)).toEqual(['true-pinch','pinch-switch']);
 expect(report.runs.every(x=>x.originalStart00&&x.startSpeedMps===52)).toBe(true);
 expect(report.runs.every(x=>x.physicalCourse.gapCell52&&x.physicalCourse.realB48Surfaces===7)).toBe(true);
 expect(report.runs.every(x=>x.normalGameLeaderboardWrites===false&&x.humanFairness==='HOLD')).toBe(true);
 expect(report.automaticallySubmitted).toBe(false);
 expect(report.realHumanTrial).toBe('UNVERIFIED_UNTIL_ACTUAL_USER_PLAY');
 expect(report.runs[0].voluntaryReport.hazardRecognizedBeforeApproach).toBe('no');
 expect(report.runs[1].voluntaryReport.enjoymentOneToFive).toBe(3);
 expect(errors).toEqual([]);
 await fs.writeFile(info.outputPath('g4e7al-QA-control-flow-not-human.json'),
  JSON.stringify({realHumanTest:false,automatedChromiumOnly:true,report,errors},null,2));
});
test('AL actual manual oversteer produces an authentic failed run with direct gameover JSON',async({page})=>{
 test.setTimeout(90000);
 await page.goto(url('TRUE-PINCH'));
 await expect(page.locator('#appStatus')).toContainText('G4E-7AL LOCAL MANUAL',{timeout:65000});
 await page.keyboard.down('KeyD');
 await expect(page.locator('#runResult')).toBeVisible({timeout:45000});
 await page.keyboard.up('KeyD');
 await expect(page.locator('#g4e7alResultDownload')).toBeVisible();
 const dl=page.waitForEvent('download');
 await page.locator('#g4e7alResultDownload').click();
 const report=JSON.parse(await fs.readFile(await(await dl).path(),'utf8'));
 const current=report.uncommittedCurrentRun;
 expect(current.road).toBe('true-pinch');
 expect(current.status).toBe('failed');
 expect(current.metrics.physicsSteps).toBeGreaterThan(0);
 expect(current.metrics.activeDirectionalSteps).toBeGreaterThan(0);
 expect(current.stopped.seconds).toBeGreaterThan(0);
 expect(current.certifiedSlope2Meters).toBe(0);
 expect(current.normalGameLeaderboardWrites).toBe(false);
 expect(report.automaticallySubmitted).toBe(false);
});
