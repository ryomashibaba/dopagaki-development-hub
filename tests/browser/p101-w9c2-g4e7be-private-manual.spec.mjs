import {test,expect} from '@playwright/test';
import fs from 'node:fs/promises';
const base='/drive3d/?g4e7al=manual&g4e7be=roll-deck';
test('BE stage is NEVER selected without the dedicated localhost explicit opt-in',async({page})=>{
 await page.goto('/drive3d/?g4e7be=roll-deck&stage=VB-P101-A13-W9C2-G4E7BC-TRUE-PINCH-ROLLDECK');
 await expect(page.locator('#stage')).toHaveValue('EP-P66');
 await expect(page.locator('#stage option[value^="VB-P101-A13-W9C2-G4E7BC-"]')).toHaveCount(0);
 await expect(page.locator('#g4e7alPanel')).toHaveCount(0);
});
test('BE authentic WebGL Chromium manual BC true/switch A-D control and local JSON',async({page},info)=>{
 test.setTimeout(160000);const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(base);
 const view=page.locator('#view'),stage=page.locator('#stage');
 await expect(view).toHaveAttribute('data-machine-count','28',{timeout:90000});
 await expect(view).toHaveAttribute('data-g4e7be-mode','real-BC-rollDeck-B48-private-manual');
 await expect(view).toHaveAttribute('data-run-mode','private-real-B48-B51-AL-manual-HOLD');
 await expect(page.locator('#appStatus')).toContainText('G4E-7BE BC ROLLDECK');
 await expect(stage).toHaveValue('VB-P101-A13-W9C2-G4E7BC-TRUE-PINCH-ROLLDECK');
 await expect(stage).toBeDisabled();
 await expect(page.locator('#spawn')).toHaveValue('0');
 await expect(page.locator('#p101Profile')).toHaveValue('OVERDRIVE');
 await expect(page.locator('#demoRun')).toBeDisabled();
 await expect(page.locator('#g4e7alPanel')).toContainText('BC rollDeck');
 await expect(page.locator('#g4e7alNext')).toBeEnabled();
 await page.keyboard.down('KeyD');await page.waitForTimeout(450);await page.keyboard.up('KeyD');
 const d0=page.waitForEvent('download');
 await page.locator('#g4e7alDownload').click();
 const snapshot=JSON.parse(await fs.readFile(await(await d0).path(),'utf8'));
 expect(snapshot.uncommittedCurrentRun.physicalCandidate).toBe('G4E7BC_ROLLDECK_PRIVATE_REAL_CROWN_CHASM');
 expect(snapshot.uncommittedCurrentRun.physicalCourse.researchBCRealContour).toBe(true);
 expect(snapshot.uncommittedCurrentRun.source).toBe('LOCAL_MANUAL_INPUT_NO_P96');
 expect(snapshot.uncommittedCurrentRun.metrics.activeDirectionalSteps).toBeGreaterThan(0);
 expect(snapshot.uncommittedCurrentRun.originalStart00).toBe(true);
 expect(snapshot.automaticallySubmitted).toBe(false);
 await view.screenshot({path:info.outputPath('g4e7be-true-b48-WebGL-not-human.png')});
 await page.locator('#g4e7alNext').click();
 await expect(stage).toHaveValue('VB-P101-A13-W9C2-G4E7BC-PINCH-SWITCH-ROLLDECK',{timeout:90000});
 await expect(view).toHaveAttribute('data-g4e7be-mode','real-BC-rollDeck-B48-private-manual');
 await page.keyboard.down('ArrowLeft');await page.waitForTimeout(430);await page.keyboard.up('ArrowLeft');
 await view.screenshot({path:info.outputPath('g4e7be-switch-b48-WebGL-not-human.png')});
 await page.locator('#g4e7alNext').click();
 await expect(page.locator('#g4e7alStep')).toContainText('比較2/2記録完了');
 const d1=page.waitForEvent('download');
 await page.locator('#g4e7alDownload').click();
 const report=JSON.parse(await fs.readFile(await(await d1).path(),'utf8'));
 expect(report.completedBoth).toBe(true);
 expect(report.runs.map(x=>x.road)).toEqual(['true-pinch','pinch-switch']);
 expect(report.runs.every(x=>x.physicalCourse.researchBCRealContour)).toBe(true);
 expect(report.runs.every(x=>x.humanFairness==='HOLD'&&x.publish==='HOLD')).toBe(true);
 expect(report.realHumanTrial).toBe('UNVERIFIED_UNTIL_ACTUAL_USER_PLAY');
 expect(errors).toEqual([]);
 await fs.writeFile(info.outputPath('g4e7be-actual-browser-only.json'),JSON.stringify({manualHumanVerified:false,webGlPageErrors:errors,report},null,2));
});
