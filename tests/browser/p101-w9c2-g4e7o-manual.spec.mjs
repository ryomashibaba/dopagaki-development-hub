import {test,expect} from '@playwright/test';
import fs from 'node:fs/promises';
const stage='VB-P101-A13-W9C2-G4E7M-THREAD';
test('G4E7O cannot be accessed from default, public, or without manual opt-in',async({page})=>{
 await page.goto('/drive3d/?g4e7o=manual&stage='+stage);
 await expect(page.locator('#stage')).toHaveValue('EP-P66');
 await expect(page.locator('#g4e7oPanel')).toHaveCount(0);
 await expect(page.locator('#view')).toHaveAttribute('data-run-mode','manual');
 await page.goto('/drive3d/?g4e7m=on&stage='+stage);
 await expect(page.locator('#appStatus')).toContainText('G4E-7M',{timeout:60000});
 await expect(page.locator('#g4e7oPanel')).toHaveCount(0);
 await expect(page.locator('#view')).toHaveAttribute('data-run-mode','private-real-B48-human-hold');
});
test('G4E7O local two manually controlled study slots and no automatic human PASS',async({page},info)=>{
 test.setTimeout(200000);
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/drive3d/?g4e7m=on&g4e7o=manual&stage='+stage);
 const view=page.locator('#view'),panel=page.locator('#g4e7oPanel');
 await expect(page.locator('#appStatus')).toContainText('G4E-7M',{timeout:70000});
 await expect(panel).toBeVisible();
 await expect(view).toHaveAttribute('data-g4e7o-mode','human-keyboard-qa-only');
 await expect(view).toHaveAttribute('data-run-mode','private-human-B48-QA-HOLD');
 await expect(view).toHaveAttribute('data-machine-count','28');
 await expect(page.locator('#spawn')).toHaveValue('0');
 await expect(page.locator('#stage')).toBeDisabled();
 await expect(page.locator('#spawn')).toBeDisabled();
 await expect(page.locator('#p101Profile')).toBeDisabled();
 await expect(page.locator('#p101Profile')).toHaveValue('OVERDRIVE');
 await expect(page.locator('#cameraCompare')).toBeDisabled();
 await expect(page.locator('#demoRun')).toBeDisabled();
 await expect(page.locator('#g4e7oStep')).toContainText('1/2');
 await expect(page.locator('#g4e7oStep')).toContainText('THREAD');
 await expect(page.locator('#g4e7oResultDownload')).toBeHidden();
 await page.screenshot({path:info.outputPath('g4e7o-manual-01-start.png'),fullPage:false});
 await page.keyboard.down('KeyD');await page.waitForTimeout(400);await page.keyboard.up('KeyD');
 await expect(page.locator('#g4e7oLive')).toContainText('路肩');
 const initialSave=page.waitForEvent('download');
 await page.locator('#g4e7oDownload').click();
 const snapshot=JSON.parse(await fs.readFile(await (await initialSave).path(),'utf8'));
 expect(snapshot.runs).toHaveLength(0);
 expect(snapshot.uncommittedCurrentRun.variant).toBe('thread');
 expect(snapshot.uncommittedCurrentRun.wasOriginalStart00).toBe(true);
 expect(snapshot.uncommittedCurrentRun.approvedSlopeDnaMeters).toBe(0);
 await page.locator('#g4e7oVisibility').selectOption('no');
 await page.locator('#g4e7oNote').fill('Playwright UI workflow only; NOT a real human quality test');
 await page.locator('#g4e7oNext').click();
 await expect(page.locator('#appStatus')).toContainText('G4E-7M',{timeout:70000});
 await expect(page.locator('#stage')).toHaveValue('VB-P101-A13-W9C2-G4E7M-PRECIPICE');
 await expect(page.locator('#spawn')).toHaveValue('0');
 await expect(page.locator('#g4e7oStep')).toContainText('2/2');
 await expect(page.locator('#g4e7oStep')).toContainText('PRECIPICE');
 await expect(view).toHaveAttribute('data-g4e7o-mode','human-keyboard-qa-only');
 await page.keyboard.down('ArrowLeft');await page.waitForTimeout(250);await page.keyboard.up('ArrowLeft');
 await page.screenshot({path:info.outputPath('g4e7o-manual-02-precipice.png'),fullPage:false});
 await page.locator('#g4e7oVisibility').selectOption('unsure');
 await page.locator('#g4e7oEnjoyment').selectOption('4');
 await page.locator('#g4e7oNext').click();
 await expect(page.locator('#g4e7oStep')).toContainText('2/2 保存準備完了');
 await expect(page.locator('#g4e7oNext')).toBeDisabled();
 await expect(view).toHaveAttribute('data-g4e7o-mode','two-trials-recorded-hold');
 const dl=page.waitForEvent('download');
 await page.locator('#g4e7oDownload').click();
 const report=JSON.parse(await fs.readFile(await (await dl).path(),'utf8'));
 expect(report.completedBoth).toBe(true);expect(report.runs).toHaveLength(2);
 expect(report.runs.map(x=>x.variant)).toEqual(['thread','precipice']);
 expect(report.runs.every(x=>x.approvedSlopeDnaMeters===0&&x.fairnessCertified===false)).toBe(true);
 expect(report.runs.every(x=>x.wasOriginalStart00&&x.originalStartSpeedMps===52)).toBe(true);
 expect(report.runs.every(x=>x.metrics.physicalSteps>=0)).toBe(true);
 expect(report.runs.every(x=>x.status!=='finished'||x.elapsedSeconds>20)).toBe(true);
 expect(report.runs.every(x=>x.humanInputNotProvenByAutomation)).toBe(true);
 expect(report.automatedUpload).toBe(false);expect(report.normalGameLeaderboardWrites).toBe(false);
 expect(report.review).toBe('HOLD');expect(report.certifiedSlope2Meters).toBe(0);
 expect(report.runs[0].voluntaryHumanReport.curveVisibleAtLeastTwoSecondsBeforeArrival).toBe('no');
 expect(report.runs[1].voluntaryHumanReport.enjoymentOneToFive).toBe(4);
 await fs.writeFile(info.outputPath('g4e7o-browser-ui-control-flow-not-human.json'),
  JSON.stringify({realHumanTest:false,automatedBrowserControlFlowOnly:true,
   report,errors,noHumanApproval:true,originalPhysicsCodeUnaffected:true},null,2));
 expect(errors).toEqual([]);
});
