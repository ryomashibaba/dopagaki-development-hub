import test from 'node:test';
import assert from 'node:assert/strict';
import {generateG4E2TrueGap,G4E2_GAP} from '../scripts/p101-w9c2-g4e2-true-gap-build.mjs';
import {generateW9C2G4ENarrow} from '../scripts/p101-w9c2-g4e-narrow-build.mjs';
import {compile,contacts} from '../private/reference_only/director/collision.js';
import {sample,tessellate} from '../private/reference_only/director/surface.js';
test('G4E-2 actual B48 void: two disjoint solid road meshes, no hidden midpoint floor, 28 unchanged machines',()=>{
 const original=generateW9C2G4ENarrow('shoulder');
 const baseline=JSON.stringify(original);
 const gap=generateG4E2TrueGap();
 const a=gap.surfaces[3],b=gap.surfaces.at(-1),world=compile(gap);
 assert.equal(gap.surfaces.length,8);
 assert.equal(gap.movingObstacles.length,28);
 assert.deepEqual(gap.movingObstacles,original.movingObstacles);
 assert.deepEqual(gap.spawns,original.spawns);
 assert.deepEqual(gap.route,original.route);
 for(let i=0;i<7;i++)if(i!==3)assert.deepEqual(gap.surfaces[i],original.surfaces[i]);
 assert.equal(a.id,original.surfaces[3].id);
 assert.equal(b.id,a.id+G4E2_GAP.landingSuffix);
 assert.equal(a.collidable,true);assert.equal(b.collidable,true);
 assert.equal(a.rideable,true);assert.equal(b.rideable,true);
 assert.equal(tessellate(a).degenerate,0);
 assert.equal(tessellate(b).degenerate,0);
 const mid=sample(original.surfaces[3],(G4E2_GAP.uTakeoff+G4E2_GAP.uLanding)/2,.5);
 const support=contacts(world,[mid[0],mid[1]+.65,mid[2]],.65).filter(c=>c.triangle.rideable);
 assert.equal(support.length,0,'No collision plane is permitted across the gap');
 assert(gap.stageForge.g4e2TrueGap.actualCenterlineEdgeDistanceMeters>5);
 assert.equal(gap.stageForge.g4e2TrueGap.naturalAirborneJumpVerified,false);
 assert.equal(gap.stageForge.g4e2TrueGap.approvedSlopeDNAMeters,0);
 assert.equal(gap.stageForge.productionPromoted,false);
 assert.equal(JSON.stringify(original),baseline);
});
